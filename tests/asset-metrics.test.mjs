import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {specimenMetrics,vesselMetrics,assetMetrics} from '../dist/asset-metrics.js';
import {specimens,browseSpecimens,vessels,dist} from './helpers/catalog.mjs';
import {drawsStem} from '../dist/scale.js?v=hn3';
import {vesselGeometry} from '../dist/geometry.js?v=28';

const stale='re-run: CANVAS_MODULE=… node qa/measure-assets.mjs';
const inUnit=v=>Number.isFinite(v)&&v>=0&&v<=1;

test('asset-metrics.js is marked as generated',()=>{
 const source=readFileSync(`${dist}asset-metrics.js`,'utf8');
 assert.match(source.split('\n')[2],/GENERATED by qa\/measure-assets\.mjs/);
});

test('every specimen has a crown, a head box and its bottom stem runs, measured at its current height',()=>{
 assert.ok(browseSpecimens.length>150);
 assert.deepEqual(specimens.filter(a=>!specimenMetrics[a.id]).map(a=>a.id),[],stale);
 for(const a of specimens){
  const m=assetMetrics(a.id);
  assert.equal(m.cm,a.height,`${a.id}: measured at ${m.cm} cm, now ${a.height} cm; ${stale}`);
  assert.ok(m.crown.length===2&&m.crown.every(inUnit),`${a.id}: crown`);
  const ratio=a.width/a.heightPx,reachOf=([u,v])=>Math.hypot((u-(a.anchor??.5))*ratio,1-v);
  if(a.tip)assert.ok(reachOf(m.crown)>=reachOf(a.tip)*.98,`${a.id}: the crown must reach at least as far from the stem base as the focus point`);
  const widthCm=a.height*a.width/a.heightPx;
  assert.ok(m.headCm.length===2&&m.headCm[0]>0&&m.headCm[1]>0&&m.headCm[0]<=widthCm*1.05+.2&&m.headCm[1]<=a.height+.2,`${a.id}: headCm ${m.headCm}`);
  assert.ok(inUnit(m.bottom)&&m.bottom>.5,`${a.id}: bottom`);
  assert.ok(m.bottomRuns.length>0,`${a.id}: no bottom runs`);
  m.bottomRuns.forEach(([u0,u1],i)=>{assert.ok(inUnit(u0)&&inUnit(u1)&&u0<u1,`${a.id}: run ${i}`);if(i)assert.ok(m.bottomRuns[i-1][1]<u0,`${a.id}: runs overlap`)});
  if(drawsStem(a))for(const [u] of a.stems)assert.ok(inUnit(u),`${a.id}: stem root`);
 }
});

test('every vessel has a foot inside its own outline, resting on the table',()=>{
 assert.deepEqual(vessels.filter(v=>!vesselMetrics[v.id]).map(v=>v.id),[],stale);
 for(const v of vessels){
  const {cm,foot}=assetMetrics(v.id),g=vesselGeometry(v);
  assert.equal(cm,v.height,`${v.id}: ${stale}`);
  assert.ok(foot.half>0&&foot.cx-foot.half>=g.left-.05&&foot.cx+foot.half<=g.left+g.width+.05,`${v.id}: foot ${JSON.stringify(foot)}`);
  assert.ok(foot.arc>=0&&foot.arc<=2.05,`${v.id}: arc`);
  assert.ok(foot.bottom>g.top+g.height*.8&&foot.bottom<=86.01,`${v.id}: bottom ${foot.bottom}`);
 }
 assert.ok(vesselMetrics['celadon-shallow-suiban'].foot.half*2>20,'the suiban foot ring spans about 22 cm');
});
